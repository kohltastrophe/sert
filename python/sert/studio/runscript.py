def say(message):
    print(f"sert studio: {message}", file=sys.stderr, flush=True)


def build_driver(opts):
    if opts.mode == "edit":
        return opts.script
    return DRIVER_TEMPLATE.format(
        sentinel=luau_string(VERDICT),
        args=luau_string(opts.args_json),
        prelude="nil" if opts.prelude is None else luau_string(opts.prelude),
        method="ExecuteRunModeAsync" if opts.mode == "run" else "ExecutePlayModeAsync",
    )


def build_warm_driver(opts) -> str:
    prelude = "nil" if opts.prelude is None else luau_string(opts.prelude)
    if opts.mode == "edit":
        return WARM_EDIT_TEMPLATE.format(
            prelude=prelude,
            script=luau_string(opts.script or ""),
            sentinel=luau_string(VERDICT),
        )
    return WARM_PLAY_TEMPLATE.format(
        sentinel=luau_string(VERDICT),
        args=luau_string(opts.args_json),
        prelude=prelude,
        timeout=max(1.0, float(opts.timeout)),
        method="ExecuteRunModeAsync" if opts.mode == "run" else "ExecutePlayModeAsync",
    )


def stage_files(opts, stage):
    os.makedirs(stage)
    place = os.path.join(stage, "place" + os.path.splitext(opts.place)[1].lower())
    shutil.copyfile(opts.place, place)
    driver_source = build_driver(opts)
    driver = os.path.join(stage, "driver.luau")
    with open(driver, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(driver_source)
    return place, driver, driver_source


def platform_name(platform=None):
    platform = sys.platform if platform is None else platform
    if platform.startswith(("win32", "cygwin")):
        return "windows"
    return "macos" if platform == "darwin" else "linux"


def windows_studio(local_appdata=None):
    local = local_appdata if local_appdata is not None else os.environ.get("LOCALAPPDATA")
    if not local:
        return None
    found = glob.glob(os.path.join(local, "Roblox", "Versions", "*", "RobloxStudioBeta.exe"))
    return max(found, key=os.path.getmtime) if found else None


def default_launcher(platform=None, local_appdata=None):
    name = platform_name(platform)
    if name == "windows":
        studio = windows_studio(local_appdata)
        return (studio, None) if studio else (
            None,
            "Roblox Studio not found under %LOCALAPPDATA%\\Roblox\\Versions; install it or pass --launcher CMD",
        )
    if name == "macos":
        return (MAC_STUDIO, None) if os.path.isfile(MAC_STUDIO) else (
            None,
            f"Roblox Studio not found at {MAC_STUDIO}; install it or pass --launcher CMD",
        )
    return None, None


def launcher_prefix(opts):
    launcher = getattr(opts, "launcher", None)
    if not launcher:
        return ["flatpak", "run", VINEGAR_APP]
    command = os.path.expanduser(os.path.expandvars(launcher))
    if os.path.isfile(command):
        return [command]
    if os.name == "nt":
        parts = shlex.split(command, posix=False)
        return [part[1:-1] if len(part) > 1 and part[0] == part[-1] == '"' else part for part in parts]
    return shlex.split(command)


def uses_vinegar(opts) -> bool:
    launcher = getattr(opts, "launcher", None)
    if not launcher:
        return True
    try:
        prefix = launcher_prefix(opts)
    except ValueError:
        return False
    return VINEGAR_APP in prefix


def uses_wine_paths(opts) -> bool:
    if uses_vinegar(opts):
        return True
    try:
        prefix = launcher_prefix(opts)
    except ValueError:
        return False
    if not prefix:
        return False
    exe = os.path.basename(prefix[0]).lower()
    return exe in ("wine", "wine64") or exe.startswith("wine-")


def studio_path(opts, path):
    path = os.path.abspath(path)
    if uses_wine_paths(opts):
        return "Z:" + os.path.splitdrive(path)[1].replace("/", "\\")
    return path


