def find_studio_log(dirs, marker, since):
    for folder in dirs:
        try:
            names = os.listdir(folder)
        except OSError:
            continue
        for name in names:
            path = os.path.join(folder, name)
            try:
                if not name.endswith(".log") or os.path.getmtime(path) < since - 5:
                    continue
                with open(path, "rb") as fh:
                    head = fh.read(16384).decode("utf-8", "replace")
            except OSError:
                continue
            if carries(head, marker):
                return path
    return None


class LogTail:
    def __init__(self, path, needle):
        self.path, self.needle, self.offset, self.carry = path, needle, 0, b""

    def found(self):
        try:
            with open(self.path, "rb") as fh:
                fh.seek(self.offset)
                data = fh.read()
        except OSError:
            return False
        if not data:
            return False
        self.offset += len(data)
        chunk = self.carry + data
        self.carry = chunk[-len(self.needle) :]
        return self.needle in chunk


def creator_output(path):
    lines, keep = [], False
    for line in read_text(path).split("\n"):
        if entry := LOG_ENTRY.match(line):
            channel, message = entry.groups()
            keep = channel in CREATOR_CHANNELS
            if keep:
                prefix = CREATOR_CHANNELS[channel]
                lines.append(message[len(prefix) :] if prefix and message.startswith(prefix) else message)
        elif keep:
            lines.append(line)
    return "\n".join(lines) + "\n" if lines else ""


def clean_exit(path):
    try:
        with open(path, "rb") as fh:
            fh.seek(0, os.SEEK_END)
            fh.seek(max(0, fh.tell() - 65536))
            return b"About to exit the application" in fh.read()
    except OSError:
        return False


def strip_echo(text, script):
    script = script.replace("\r\n", "\n")
    echo = "> " + script
    if (at := text.find(echo)) >= 0:
        end = at + len(echo) + (1 if text.startswith("\n", at + len(echo)) else 0)
        return text[:at] + text[end:]
    lines = text.split("\n")
    wanted = script.rstrip("\n").split("\n")
    for index, line in enumerate(lines):
        if line.rstrip() != ("> " + wanted[0]).rstrip():
            continue
        count = 1
        while (
            count < len(wanted)
            and index + count < len(lines)
            and lines[index + count].rstrip() == wanted[count].rstrip()
        ):
            count += 1
        if count == len(wanted):
            end = index + count
            if end < len(lines) and not lines[end].strip():
                end += 1
            return "\n".join(lines[:index] + lines[end:])
    return text


def last_result_line(text):
    prefix, found = VERDICT + " ", None
    for line in text.split("\n"):
        if line.startswith(prefix):
            found = line[len(prefix) :].strip()
    return found


def settle(path, quiet=2.0, limit=10.0):
    deadline, size, since = time.monotonic() + limit, file_size(path), time.monotonic()
    while time.monotonic() < deadline and time.monotonic() - since < quiet:
        time.sleep(0.25)
        if file_size(path) != size:
            size, since = file_size(path), time.monotonic()


def is_json(text):
    try:
        json.loads(text)
        return True
    except ValueError:
        return False


def collect_output(out_path, studio_log, driver_source):
    text = strip_echo(read_text(out_path), driver_source)
    line = last_result_line(text)
    if studio_log and (line is None or not is_json(line)):
        settle(studio_log)
        rebuilt = strip_echo(creator_output(studio_log), driver_source)
        rebuilt_line = last_result_line(rebuilt)
        use = (
            (bool(rebuilt.strip()) and (rebuilt_line is not None or len(rebuilt) > len(text)))
            if line is None
            else (rebuilt_line is not None and is_json(rebuilt_line))
        )
        if use:
            why = "has no result line" if line is None else "has a result line that is not JSON"
            say(f"the output file {why}; the output comes from Studio's own log")
            text = rebuilt
    return text


def launcher_tail(stage, count=15):
    lines = [line for line in read_text(os.path.join(stage, "launcher.out")).split("\n") if line.strip()]
    return ("\nlauncher output:\n  " + "\n  ".join(lines[-count:])) if lines else ""


def execute_warm(opts) -> Outcome:
    link_cmd = find_studio_link()
    if link_cmd is None:
        return Outcome(
            INFRA,
            "error",
            "--warm requires studio_link.py (set STUDIO_LINK or install the roblox-dev Studio bridge)",
        )
    code = build_warm_driver(opts)
    argv = list(link_cmd)
    if opts.studio_id:
        argv.extend(["--studio", str(opts.studio_id)])
    argv.extend(["exec", "--code", code])
    try:
        done = subprocess.run(
            argv,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=opts.timeout,
        )
    except subprocess.TimeoutExpired:
        return Outcome(TIMEOUT, "timeout", f"warm Studio session timed out after {opts.timeout:g} s")
    except KeyboardInterrupt:
        return Outcome(INTERRUPTED, "interrupted", "warm Studio session interrupted")
    except OSError as err:
        return Outcome(INFRA, "error", f"could not execute studio_link: {err}")

    if done.returncode != 0:
        detail = (done.stderr or done.stdout).strip()
        return Outcome(INFRA, "error", f"studio_link exited with code {done.returncode}: {detail}", output=done.stdout)

    raw_stdout = done.stdout.strip()
    output = done.stdout
    decoded_result = None
    try:
        decoded = json.loads(raw_stdout)
        if isinstance(decoded, dict):
            if isinstance(decoded.get("output"), str):
                output = decoded["output"]
            if isinstance(decoded.get("result"), dict):
                decoded_result = decoded["result"]
            elif isinstance(decoded.get("result"), str):
                inner = json.loads(decoded["result"])
                if isinstance(inner, dict):
                    if isinstance(inner.get("output"), str):
                        output = inner["output"]
                    decoded_result = inner
    except ValueError:
        pass

    line = last_result_line(output)
    if line is not None:
        try:
            result = json.loads(line)
        except ValueError as err:
            return Outcome(INFRA, "error", f"the result line is not JSON ({err}): {line[:300]}", output=output)
    elif decoded_result is not None:
        result = decoded_result
    else:
        return Outcome(INFRA, "error", "warm Studio session returned without printing a result line", output=output)
    failed = reports_failure(result)
    message = "the result reports failure" if failed else "the result reports success"
    return Outcome(1 if failed else 0, "failed" if failed else "passed", message, result=result, output=output)


def run_attempt(opts, stage, run_id, place, driver, driver_source):
    global CURRENT
    out_name = "output.log"
    out_path = os.path.join(stage, out_name)
    marker = (run_id, out_name)
    prefix = launcher_prefix(opts)
    argv = prefix + [
        "-task",
        "RunScript",
        "-localPlaceFile",
        studio_path(opts, place),
        "-runScriptFile",
        studio_path(opts, driver),
        "-outputFile",
        studio_path(opts, out_path),
        "-quitAfterExecution",
    ]
    before = studio_processes(process_table())
    started_wall, started = time.time(), time.monotonic()
    try:
        with open(os.path.join(stage, "launcher.out"), "wb") as log:
            child = subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT, **DETACHED)
    except OSError as err:
        return Outcome(INFRA, "error", f"could not start {argv[0]}: {err}")
    attempt = CURRENT = Attempt(child, marker, before)
    say(f"launched {' '.join(prefix)} (pid {child.pid})")

    is_vinegar = uses_vinegar(opts)
    studio_log = tail = signin_tail = result_seen = signin_seen = child_exit = None
    note = ""
    needle = f"[FLog::CreatorOutput] {VERDICT} ".encode("utf-8")
    deadline = started + opts.timeout
    while True:
        now = time.monotonic()
        table = process_table()
        ours = studio_processes(table, marker) - before
        for pid in sorted(ours - attempt.tracked):
            attempt.tracked.add(pid)
            say(f"Studio is pid {pid}")
        code = child.poll()
        if code is not None and child_exit is None:
            child_exit = now
        if studio_log is None and (studio_log := find_studio_log(studio_log_dirs(opts), marker, started_wall)):
            tail = LogTail(studio_log, needle)
            signin_tail = LogTail(studio_log, SIGNIN_NEEDLE)
        if tail is not None and result_seen is None and tail.found():
            result_seen = now
        if signin_tail is not None and signin_seen is None and signin_tail.found():
            signin_seen = now
        if signin_seen is not None and result_seen is None and file_size(out_path) == 0 and now - signin_seen >= SIGNIN_GRACE:
            stopped = stop(opts, attempt)
            what = ", ".join(stopped) if stopped else "Studio"
            return Outcome(
                INFRA,
                "error",
                f"Roblox Studio is signed out (waiting at Quick Sign-In; killed {what}); sign in to Studio once and retry",
                studio_log=studio_log,
            )
        if ours or (not is_vinegar and code is None):
            if result_seen is not None and now - result_seen > QUIT_GRACE:
                note = (
                    f"Studio printed its result but had not quit {QUIT_GRACE:.0f} s later; killed "
                    + ", ".join(stop(opts, attempt))
                )
                say(note)
                break
        elif attempt.tracked:
            break
        elif child_exit is not None:
            if not is_vinegar and (table is None or file_size(out_path) > 0):
                break
            if now - child_exit > (LAUNCH_GRACE if code == 0 else LAUNCH_ERROR_GRACE):
                return Outcome(
                    INFRA,
                    "error",
                    f"Studio did not start: {prefix[0]} exited with code {code}, and no Studio process with this"
                    f" run's paths appeared{launcher_tail(stage)}",
                    studio_log=studio_log,
                )
        if now >= deadline:
            stopped = stop(opts, attempt)
            what = ", ".join(stopped) if stopped else "nothing (no Studio of this run was running)"
            if result_seen is not None:
                note = f"Studio printed its result but had not quit by the {opts.timeout:g} s timeout; killed {what}"
                say(note)
                break
            studio_log = studio_log or find_studio_log(studio_log_dirs(opts), marker, started_wall)
            output = collect_output(out_path, studio_log, driver_source)
            line = last_result_line(output)
            if line is not None and is_json(line):
                note = f"Studio produced a result before cleanup at the {opts.timeout:g} s timeout; killed {what}"
                break
            return Outcome(
                TIMEOUT,
                "timeout",
                f"timed out after {opts.timeout:g} s; killed {what}",
                output=output,
                studio_log=studio_log,
            )
        time.sleep(POLL_SECONDS)

    if is_vinegar:
        linger = time.monotonic() + LAUNCHER_LINGER
        while child.poll() is None and time.monotonic() < linger:
            time.sleep(0.25)
    say(f"Studio finished after {time.monotonic() - started:.1f} s")
    studio_log = studio_log or find_studio_log(studio_log_dirs(opts), marker, started_wall)
    output = collect_output(out_path, studio_log, driver_source)
    line = last_result_line(output)
    if line is None:
        why = (
            "Studio ended without its shutdown line (a crash?) and printed no result line"
            if studio_log and not clean_exit(studio_log)
            else "Studio quit without printing a result line"
        )
        return Outcome(
            INFRA,
            "error",
            f"{why}; Studio log: {studio_log or 'not found'}",
            output=output,
            studio_log=studio_log,
        )
    try:
        result = json.loads(line)
    except ValueError as err:
        return Outcome(
            INFRA,
            "error",
            f"the result line is not JSON ({err}): {line[:300]}",
            output=output,
            studio_log=studio_log,
        )
    failed = reports_failure(result)
    message = note or ("the result reports failure" if failed else "the result reports success")
    return Outcome(
        1 if failed else 0,
        "failed" if failed else "passed",
        message,
        result=result,
        output=output,
        studio_log=studio_log,
    )


def options(
    place,
    mode,
    *,
    script,
    args,
    prelude,
    timeout,
    keep,
    launcher,
    warm=False,
    studio_id=None,
):
    if mode not in MODES:
        raise SertError(f"unknown mode {mode!r} (edit, play or run)")
    if (mode == "edit") != (script is not None):
        raise SertError("edit mode runs a script; play and run mode take none")
    if not math.isfinite(timeout) or timeout <= 0:
        raise SertError("--timeout must be finite and positive")
    try:
        args_json = json.dumps({} if args is None else args, allow_nan=False)
    except ValueError as err:
        raise SertError(f"the request is not JSON: {err}") from None
    opts = Options(
        place,
        mode,
        script=script,
        args_json=args_json,
        prelude=prelude,
        timeout=timeout,
        keep=keep,
        launcher=launcher,
        warm=warm,
        studio_id=studio_id,
    )
    if launcher is not None:
        try:
            if not launcher_prefix(opts):
                raise SertError("--launcher is empty")
        except ValueError as err:
            raise SertError(f"--launcher: {err}") from None
    return opts


def execute(opts, run_id, stage):
    try:
        try:
            place, driver, driver_source = stage_files(opts, stage)
        except OSError as err:
            return Outcome(INFRA, "error", f"could not stage the run in {stage}: {err}")
        say(f"run {run_id}: staged in {stage}")
        return run_attempt(opts, stage, run_id, place, driver, driver_source)
    except KeyboardInterrupt:
        stopped = (stop(opts, CURRENT) if CURRENT is not None else []) + stop_run(opts, stage)
        return Outcome(INTERRUPTED, "interrupted", "interrupted; killed " + (", ".join(stopped) or "nothing"))
    finally:
        stop_strays(opts, stage)
        if opts.keep and os.path.isdir(stage):
            say(f"kept {stage}")
        else:
            shutil.rmtree(stage, ignore_errors=True)


def run(
    place,
    *,
    mode,
    report,
    script=None,
    args=None,
    prelude=None,
    timeout=300.0,
    keep=False,
    launcher=None,
    warm=False,
    studio_id=None,
):
    global CURRENT
    opts = options(
        place,
        mode,
        script=script,
        args=args,
        prelude=prelude,
        timeout=timeout,
        keep=keep,
        launcher=launcher,
        warm=warm,
        studio_id=studio_id,
    )
    main_thread = threading.current_thread() is threading.main_thread()
    previous = signal.getsignal(signal.SIGTERM) if main_thread else None
    CURRENT = None
    try:
        if main_thread:
            signal.signal(signal.SIGTERM, interrupt)
        started = time.monotonic()
        run_id = f"{time.strftime('%Y%m%d-%H%M%S')}-{os.getpid()}-{uuid.uuid4().hex[:4]}"
        stage = None
        if opts.warm:
            outcome = execute_warm(opts)
        else:
            problem = None
            if opts.launcher is None:
                opts.launcher, problem = default_launcher()
            stage = os.path.join(stage_root(opts), run_id)
            problem = problem or vinegar_problem(opts)
            outcome = Outcome(INFRA, "error", problem) if problem else execute(opts, run_id, stage)
        seconds = time.monotonic() - started
        say(f"{outcome.status} (exit {outcome.code}) in {seconds:.1f} s: {outcome.message}")
        document = {
            "exitCode": outcome.code,
            "status": outcome.status,
            "message": outcome.message,
            "result": outcome.result,
            "output": outcome.output,
            "seconds": round(seconds, 1),
            "runId": run_id,
            "stageDir": stage if stage and opts.keep and os.path.isdir(stage) else None,
            "studioLog": outcome.studio_log,
        }
        try:
            with open(report, "w", encoding="utf-8", errors="replace") as fh:
                json.dump(document, fh, ensure_ascii=False, indent=2)
                fh.write("\n")
        except OSError as err:
            say(f"cannot write the report {report}: {err.strerror or err}")
            return outcome.code or INFRA
        return outcome.code
    finally:
        CURRENT = None
        if main_thread:
            signal.signal(signal.SIGTERM, previous)
