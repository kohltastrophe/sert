VERSION = "0.744.0.7441077"
COMMIT = "61dc5e378292877dd1f32724051b1f64608f631a"
DUMP_URL = f"https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/{COMMIT}/Full-API-Dump.json"

ROOT = Path(__file__).resolve().parent.parent
OUT_FILE = ROOT / "src" / "doubles" / "generated.luau"
HEADER = f"-- Generated by scripts/gen_api.py from Roblox {VERSION} (Roblox-Client-Tracker {COMMIT[:12]}); do not edit."

ALLOWED = {"None", "PluginSecurity"}
CLASS_TAGS = {
    "NotCreatable": "C",
    "Service": "S",
    "Deprecated": "D",
    "NotBrowsable": "B",
    "NotReplicated": "N",
    "PlayerReplicated": "P",
}
MEMBER_TAGS = {"ReadOnly": "r", "WriteOnly": "w", "Deprecated": "d", "NotReplicated": "n", "Yields": "y", "NotBrowsable": "b"}
NUMERIC = {
    "Vector2", "Vector3", "Vector2int16", "Vector3int16", "Color3", "CFrame", "Rect", "UDim", "UDim2", "Ray",
    "NumberRange", "NumberSequence", "ColorSequence",
}


def load_dump() -> dict:
    sys.path.insert(0, str(ROOT / "python"))
    try:
        from sert.fetch import cache_dir, read_url
        from sert.util import SertError, write_atomic
    finally:
        sys.path.pop(0)
    try:
        path = cache_dir() / "roblox-api-dump" / COMMIT / "Full-API-Dump.json"
        if not path.is_file():
            path.parent.mkdir(parents=True, exist_ok=True)
            write_atomic(path, read_url(DUMP_URL))
    except SertError as err:
        raise SystemExit(str(err)) from err
    return json.loads(path.read_bytes())


def type_name(t: dict) -> str:
    cat, name = t["Category"], t["Name"]
    return f"Enum.{name}" if cat == "Enum" else f"@{name}" if cat == "Class" else name


def tags_of(m: dict) -> list[str]:
    return [t for t in m.get("Tags", []) if isinstance(t, str)]


def security(m: dict) -> tuple[str, str]:
    s = m["Security"]
    return (s["Read"], s["Write"]) if isinstance(s, dict) else (s, s)


def visible(m: dict) -> bool:
    tags = tags_of(m)
    return "Hidden" not in tags and "NotScriptable" not in tags and security(m)[0] in ALLOWED


def flags_of(m: dict) -> str:
    out = {MEMBER_TAGS[t] for t in tags_of(m) if t in MEMBER_TAGS}
    read, write = security(m)
    if m["MemberType"] == "Property" and write not in ALLOWED:
        out.add("r")
    if "PluginSecurity" in (read, write):
        out.add("p")
    return "".join(sorted(out))


def number(text: str) -> str:
    t = text.strip()
    if t.upper() in ("INF", "+INF"):
        return "inf"
    if t.upper() == "-INF":
        return "-inf"
    val = float(t)
    return str(int(val)) if val == int(val) and abs(val) < 2**53 else repr(float(f"{val:.15g}"))


def numbers(text: str) -> str:
    return ",".join(number(n) for n in re.split(r"[\s,{}]+", text) if n)


def escape_text(text: str) -> str:
    return text.replace("%", "%25").replace("\n", "%0A").replace("\r", "%0D").replace(";", "%3B")


def default_of(m: dict) -> str:
    raw = m.get("Default")
    if not isinstance(raw, str) or raw.startswith("__api_dump_"):
        return ""
    cat, name = m["ValueType"]["Category"], m["ValueType"]["Name"]
    if cat == "Primitive":
        if name == "bool":
            return raw if raw in ("true", "false") else ""
        if name in ("int", "int64", "float", "double"):
            try:
                return number(raw)
            except ValueError:
                return ""
        return "=" + escape_text(raw) if name == "string" else ""
    if cat == "Enum":
        return raw
    if cat == "DataType":
        if name in NUMERIC:
            try:
                return numbers(raw)
            except ValueError:
                return ""
        if name in ("Axes", "Faces"):
            return ",".join(p.strip() for p in raw.split(",") if p.strip()) or "-"
        if name == "ContentId":
            return "=" + escape_text(raw)
        if name == "TweenInfo":
            fields = dict(p.split(":", 1) for p in raw.split())
            keys = ("Time", "EasingStyle", "EasingDirection", "RepeatCount", "Reverses", "DelayTime")
            vals = [number(fields[k]) if k in ("Time", "RepeatCount", "DelayTime") else fields[k] for k in keys]
            return ",".join(v.lower() if v in ("True", "False") else v for v in vals)
    return ""


def params_of(m: dict) -> str:
    return ",".join(f"{p['Name']}{'?' if 'Default' in p else ''}:{type_name(p['Type'])}" for p in m.get("Parameters", []))


def returns_of(m: dict) -> str:
    r = m.get("ReturnType")
    return "" if r is None else ",".join(type_name(t) for t in (r if isinstance(r, list) else [r]))


def encode_class(c: dict, abstract: bool) -> str:
    tags = "".join(sorted(CLASS_TAGS[t] for t in tags_of(c) if t in CLASS_TAGS)) + ("A" if abstract else "")
    lines = [f"{c['Superclass'] if c['Superclass'] != '<<<ROOT>>>' else ''}|{tags}"]
    for m in c["Members"]:
        if not visible(m):
            continue
        kind, name, flags = m["MemberType"], m["Name"], flags_of(m)
        if kind == "Property":
            lines.append(f"P {name}|{type_name(m['ValueType'])}|{flags}|{default_of(m)}")
        elif kind == "Event":
            lines.append(f"E {name}|{flags}|{params_of(m)}")
        elif kind in ("Function", "Callback"):
            lines.append(f"{kind[0]} {name}|{flags}|{params_of(m)}|{returns_of(m)}")
    return ";".join(lines)


def quoted(text: str) -> str:
    body = text.replace("\\", "\\\\")
    if '"' in text and "'" not in text:
        return "'" + body + "'"
    return '"' + body.replace('"', '\\"') + '"'


def key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else f"[{quoted(name)}]"


