def render_module(dump: dict) -> str:
    classes = sorted(dump["Classes"], key=lambda c: c["Name"])
    parents = {c["Superclass"] for c in classes}
    out = [HEADER, "--!strict", "local CLASSES: { [string]: string } = {"]
    for c in classes:
        tags = tags_of(c)
        abstract = "NotCreatable" in tags and "Service" not in tags and c["Name"] in parents
        out.append(f"\t{key(c['Name'])} = {quoted(encode_class(c, abstract))},")
    out += ["}", "", "local ENUMS: { [string]: string } = {"]
    for e in sorted(dump["Enums"], key=lambda e: e["Name"]):
        items = []
        for item in e["Items"]:
            items.append(f"{item['Name']}={item['Value']}")
            items += [f"{alias}={item['Value']}!" for alias in item.get("LegacyNames", [])]
        out.append(f"\t{key(e['Name'])} = {quoted(';'.join(items))},")
    out.append("}")
    out.append(LOADER_LUAU.rstrip("\n"))
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when src/doubles/generated.luau is out of date")
    args = parser.parse_args(argv)
    text = render_module(load_dump())
    if args.check:
        if not OUT_FILE.is_file() or OUT_FILE.read_text(encoding="utf-8") != text:
            print(f"gen_api: {OUT_FILE.relative_to(ROOT)} is out of date; run python3 scripts/gen_api.py", file=sys.stderr)
            return 1
        return 0
    OUT_FILE.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_api: wrote {OUT_FILE.relative_to(ROOT)} ({len(text.encode()):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
